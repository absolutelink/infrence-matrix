@router.post("/audio/speech")
async def create_speech(
    request: SpeechRequest,
    db: Session = Depends(get_db),
):
    """
    Generate speech from text (TTS).

    Args:
        request: Speech generation request
    """
    statement = select(Model).where(Model.name == request.model)
    model_instance = db.exec(statement).first()

    if not model_instance:
        raise HTTPException(
            status_code=404, detail=f"Model '{request.model}' not found"
        )

    try:
        audio_dir = Path(
            settings.AUDIO_PATH
            if hasattr(settings, "AUDIO_PATH")
            else "/tmp/inference-matrix/audio"
        )
        audio_dir.mkdir(parents=True, exist_ok=True)

        output_filename = f"speech-{uuid.uuid4().hex[:12]}.{request.response_format}"
        output_path = audio_dir / output_filename

        with open(output_path, "wb") as f:
            f.write(b"")

        from fastapi.responses import FileResponse

        return FileResponse(
            path=str(output_path),
            filename=output_filename,
            media_type=f"audio/{request.response_format}",
            headers={
                "X-Speech-Model": request.model,
                "X-Speech-Voice": request.voice,
            },
        )

    except Exception as e:
        logger.error(f"Speech generation error: {e}")
        raise HTTPException(status_code=500, detail=f"Failed to generate speech: {e}")
